// Generates contracts/LeanSphincsVerifier.sol, the gas-optimised leanSPHINCS verifier. It performs the same verification
// as contracts/LeanSphincsVerifierReference.sol, the readable version, with the WOTS+C chains of a layer, the levels of
// every Merkle path and three FORS trees per loop iteration unrolled. `--check` fails if the committed file differs.
//
// Three FORS trees per iteration measured the lowest gas on Anvil 1.7.1 (Solidity 0.8.28 via IR, optimizer 200,
// Cancun; wallet known-answer signature): one tree per iteration 77,319 gas, three 76,615, six 76,727, eight 80,139,
// all 24 unrolled 79,376 with 25,652 bytes of runtime, above the 24,576-byte limit of EIP-170.
const FORS_TREES_PER_ITERATION = 3;
if (24 % FORS_TREES_PER_ITERATION) throw Error('FORS_TREES_PER_ITERATION must divide 24');

const HIGH = '0xffffffffffffffffffffffffffffffff00000000000000000000000000000000';
const M33 = '0x33333333333333333333333333333333';
const M0F = '0x0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f';
const M01 = '0x01010101010101010101010101010101';
const hex = n => '0x' + n.toString(16);
const out = [];
const L = (indent, text) => out.push(' '.repeat(indent) + text);

// One Merkle level z (1-based) of a path whose leaf index is `index`: ADRS word2 = z, word3 = node index at height z,
// the current node placed left or right by bit z-1 of the index, the sibling copied from `sibling` into the other half.
// The offset is that bit moved to 0x10 by one shift and one mask (the technique of SphincsVerifier_v5).
function level(indent, z, adrsExpr, index, sibling) {
  const bit = z === 5 ? index : z < 5 ? `shl(${5 - z}, ${index})` : `shr(${z - 5}, ${index})`;
  L(indent, `{`);
  L(indent + 4, `let o := and(${bit}, 0x10)`);
  L(indent + 4, `mstore(0x10, ${adrsExpr})`);
  L(indent + 4, `mstore(add(0x30, o), node)`);
  L(indent + 4, `calldatacopy(sub(0x40, o), ${sibling}, 16)`);
  L(indent + 4, `node := keccak256(0x00, 0x50)`);
  L(indent, `}`);
}

