/* ═══════════════════════════════════════════════════════════════════
   DashboardHeader — top bar with logo, identity, and action icons
   ───────────────────────────────────────────────────────────────────
   Shows:
     - Logo + wallet name ("nicetry")
     - Seed identifier label ("Seed Phrase 1 #1") — for now we only
       support one seed per vault, so this is static; wire it to real
       data when you add multi-seed support
     - Button to toggle the settings menu (popup ↔ sidebar switch is
       now inside the settings menu, dynamic based on current uiMode)

   The settings menu is rendered by the parent (Dashboard.jsx) so this
   component only fires the toggle callback.
   ═══════════════════════════════════════════════════════════════════ */

import { smartAddr, accounts, activeAccountIndex } from "@/ui/store.js";
import { useNetwork } from "@/ui/hooks/useNetwork.js";

